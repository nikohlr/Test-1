import { useEffect, useRef, useState } from "react";
import { api } from "../api/client";
import type { AiSuggestion, Message } from "../api/types";

const REFINE_ACTIONS = [
  { label: "kürzer", instruction: "Formuliere den Text kürzer." },
  { label: "freundlicher", instruction: "Formuliere den Text freundlicher." },
  { label: "lockerer", instruction: "Formuliere den Text in einem lockeren Ton." },
  { label: "professioneller", instruction: "Formuliere den Text professioneller." },
  { label: "Rückfrage ergänzen", instruction: "Ergänze eine passende Rückfrage an den Kunden." },
  { label: "Termin vorschlagen", instruction: "Schlage einen Termin zur Besichtigung vor." },
  { label: "Angebot ankündigen", instruction: "Kündige an, dass in Kürze ein Angebot folgt." },
  { label: "korrigieren", instruction: "Korrigiere Rechtschreibung und Grammatik." },
  { label: "neu formulieren", instruction: "Formuliere den Text komplett neu." },
];

const SUGGESTION_LABELS: Record<string, string> = {
  REPLY_SHORT: "kurz und direkt",
  REPLY_FRIENDLY: "freundlich und persönlich",
  REPLY_PROFESSIONAL: "professionell und ausführlich",
};

function statusIcon(status: string) {
  switch (status) {
    case "SENT":
      return "✓";
    case "DELIVERED":
      return "✓✓";
    case "READ":
      return "✓✓ (gelesen)";
    case "FAILED":
      return "⚠ fehlgeschlagen";
    default:
      return "…";
  }
}

function MessageBubble({ message }: { message: Message }) {
  if (message.isInternalNote) {
    return (
      <div className="msg-row note-row">
        <div className="bubble note-bubble">
          <div className="note-label">Interne Notiz</div>
          {message.text}
        </div>
      </div>
    );
  }
  if (message.messageType === "SYSTEM_NOTE") {
    return (
      <div className="msg-row system-row">
        <div className="bubble system-bubble">{message.text}</div>
      </div>
    );
  }

  const isOutbound = message.direction === "OUTBOUND";
  return (
    <div className={`msg-row ${isOutbound ? "outbound" : "inbound"}`}>
      <div className={`bubble ${isOutbound ? "outbound-bubble" : "inbound-bubble"}`}>
        {message.isAiGenerated && <div className="ai-tag">KI-generiert{message.aiApprovedByUser ? "" : " (Entwurf)"}</div>}

        {message.messageType === "IMAGE" && message.mediaUrl && (
          <img src={message.mediaUrl} alt="Bild" className="msg-media-image" />
        )}
        {message.messageType === "DOCUMENT" && message.mediaUrl && (
          <a href={message.mediaUrl} target="_blank" rel="noreferrer" className="msg-document">
            📄 Dokument öffnen
          </a>
        )}
        {(message.messageType === "QUOTE_PDF" || message.messageType === "INVOICE_PDF") && message.mediaUrl && (
          <a href={message.mediaUrl} target="_blank" rel="noreferrer" className="msg-document">
            📎 {message.messageType === "QUOTE_PDF" ? "Angebot" : "Rechnung"} (PDF)
          </a>
        )}
        {message.messageType === "AUDIO" && (
          <div>
            {message.mediaUrl && <audio controls src={message.mediaUrl} />}
            {message.voiceTranscript && (
              <div className="voice-transcript">
                <em>{message.voiceTranscript.isAutoGenerated ? "Automatisch erzeugtes Transkript:" : "Transkript:"}</em>
                <div>{message.voiceTranscript.transcriptText}</div>
              </div>
            )}
          </div>
        )}
        {message.messageType === "LOCATION" && <div>📍 {message.text}</div>}
        {(message.messageType === "TEXT" || !message.mediaUrl) && message.text && <div>{message.text}</div>}

        <div className="bubble-meta">
          <span>{new Date(message.createdAt).toLocaleTimeString("de-DE", { hour: "2-digit", minute: "2-digit" })}</span>
          {isOutbound && <span> · {statusIcon(message.deliveryStatus)}</span>}
        </div>
      </div>
    </div>
  );
}

export default function MessageThread({ conversationId }: { conversationId: string | null }) {
  const [messages, setMessages] = useState<Message[]>([]);
  const [draft, setDraft] = useState("");
  const [suggestions, setSuggestions] = useState<AiSuggestion[]>([]);
  const [generatingAi, setGeneratingAi] = useState(false);
  const [showNoteBox, setShowNoteBox] = useState(false);
  const [noteText, setNoteText] = useState("");
  const [summary, setSummary] = useState<string | null>(null);
  const bottomRef = useRef<HTMLDivElement>(null);

  function loadMessages() {
    if (!conversationId) return;
    api.get<Message[]>(`/conversations/${conversationId}/messages`).then(setMessages);
  }

  useEffect(() => {
    setSuggestions([]);
    setDraft("");
    setSummary(null);
    if (conversationId) {
      loadMessages();
      api.post(`/conversations/${conversationId}/read`);
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [conversationId]);

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [messages]);

  if (!conversationId) {
    return <div className="message-thread empty-hint">Wählen Sie links eine Unterhaltung aus.</div>;
  }

  async function send() {
    if (!draft.trim() || !conversationId) return;
    await api.post(`/conversations/${conversationId}/messages`, { text: draft });
    setDraft("");
    setSuggestions([]);
    loadMessages();
  }

  async function generateAiSuggestions() {
    if (!conversationId) return;
    setGeneratingAi(true);
    try {
      const created = await api.post<AiSuggestion[]>(`/conversations/${conversationId}/ai-suggestions`);
      setSuggestions(created);
    } catch (err: any) {
      alert(err.message);
    } finally {
      setGeneratingAi(false);
    }
  }

  async function refine(suggestion: AiSuggestion, instruction: string) {
    const updated = await api.post<AiSuggestion>(`/conversations/ai-suggestions/${suggestion.id}/refine`, { instruction });
    setSuggestions((prev) => prev.map((s) => (s.id === updated.id ? updated : s)));
  }

  async function useSuggestion(suggestion: AiSuggestion) {
    setDraft(suggestion.editedText ?? suggestion.generatedText);
  }

  async function addNote() {
    if (!noteText.trim() || !conversationId) return;
    await api.post(`/conversations/${conversationId}/notes`, { text: noteText });
    setNoteText("");
    setShowNoteBox(false);
    loadMessages();
  }

  async function summarize() {
    if (!conversationId) return;
    const res = await api.post<{ summary: string }>(`/conversations/${conversationId}/summarize`);
    setSummary(res.summary);
  }

  return (
    <div className="message-thread">
      <div className="thread-toolbar">
        <button onClick={summarize}>Gespräch zusammenfassen</button>
        <button onClick={() => setShowNoteBox((v) => !v)}>Interne Notiz</button>
      </div>
      {summary && (
        <div className="summary-banner">
          <strong>Zusammenfassung:</strong> {summary}
        </div>
      )}
      <div className="messages-scroll">
        {messages.map((m) => (
          <MessageBubble key={m.id} message={m} />
        ))}
        <div ref={bottomRef} />
      </div>

      {showNoteBox && (
        <div className="note-composer">
          <div className="note-label">Interne Notiz (wird niemals an den Kunden gesendet)</div>
          <textarea value={noteText} onChange={(e) => setNoteText(e.target.value)} rows={2} />
          <button onClick={addNote} disabled={!noteText.trim()}>
            Notiz speichern
          </button>
        </div>
      )}

      {suggestions.length > 0 && (
        <div className="ai-suggestions">
          {suggestions.map((s) => (
            <div key={s.id} className="ai-suggestion-card">
              <div className="ai-suggestion-type">{SUGGESTION_LABELS[s.suggestionType] ?? s.suggestionType}</div>
              <div className="ai-suggestion-text">{s.editedText ?? s.generatedText}</div>
              <div className="ai-suggestion-actions">
                <button onClick={() => useSuggestion(s)}>verwenden</button>
                {REFINE_ACTIONS.map((r) => (
                  <button key={r.label} className="small" onClick={() => refine(s, r.instruction)}>
                    {r.label}
                  </button>
                ))}
              </div>
            </div>
          ))}
        </div>
      )}

      <div className="composer">
        <button className="ai-generate-btn" onClick={generateAiSuggestions} disabled={generatingAi}>
          {generatingAi ? "Erzeuge Vorschläge…" : "✨ Antwort mit KI erstellen"}
        </button>
        <textarea
          placeholder="Nachricht schreiben…"
          value={draft}
          onChange={(e) => setDraft(e.target.value)}
          rows={3}
        />
        <button className="send-btn" onClick={send} disabled={!draft.trim()}>
          Senden
        </button>
      </div>
    </div>
  );
}
