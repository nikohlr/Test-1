export interface Customer {
  id: string;
  firstName?: string | null;
  lastName?: string | null;
  companyName?: string | null;
  phoneNumber?: string | null;
  email?: string | null;
  street?: string | null;
  city?: string | null;
  status: "LEAD" | "ACTIVE" | "INACTIVE" | "ARCHIVED";
  notes?: string | null;
}

export interface User {
  id: string;
  name: string;
  email: string;
  role: string;
}

export interface ConversationListItem {
  id: string;
  customer: Customer | null;
  channel: string;
  phoneNumber: string | null;
  status: "OPEN" | "PENDING" | "ARCHIVED";
  assignedUser: User | null;
  unreadCount: number;
  urgency: number;
  lastMessage: Message | null;
  lastMessageAt: string | null;
  openTask: { id: string; title: string } | null;
  latestInquiry: { id: string; desiredService?: string | null; status: string } | null;
}

export interface Message {
  id: string;
  conversationId: string;
  direction: "INBOUND" | "OUTBOUND";
  sender?: string | null;
  recipient?: string | null;
  messageType: string;
  text?: string | null;
  mediaUrl?: string | null;
  deliveryStatus: "PENDING" | "SENT" | "DELIVERED" | "READ" | "FAILED";
  isAiGenerated: boolean;
  aiApprovedByUser: boolean;
  isInternalNote: boolean;
  createdAt: string;
  errorMessage?: string | null;
  media?: { id: string; category?: string | null; storageUrl: string; aiDescription?: string | null; aiDescriptionIsEstimate: boolean } | null;
  voiceTranscript?: { id: string; transcriptText: string; isAutoGenerated: boolean; correctedByUser: boolean } | null;
  aiSuggestions?: AiSuggestion[];
}

export interface AiSuggestion {
  id: string;
  suggestionType: string;
  generatedText: string;
  editedText?: string | null;
  status: string;
}

export interface CustomerDraft {
  id: string;
  customerId?: string | null;
  conversationId?: string | null;
  extractedData: Record<string, unknown>;
  confidence?: Record<string, number> | null;
  status: "PENDING" | "CONFIRMED" | "REJECTED";
  createdAt: string;
}

export interface MessageTemplate {
  id: string;
  channel: string;
  internalName: string;
  externalTemplateName?: string | null;
  language: string;
  category?: string | null;
  content: string;
  approvalStatus: "DRAFT" | "PENDING" | "APPROVED" | "REJECTED" | "DISABLED";
  active: boolean;
  lastSyncedAt?: string | null;
}

export interface PendingAction {
  id: string;
  toolName: string;
  preview: string;
}
