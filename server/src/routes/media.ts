import { Router } from "express";
import { z } from "zod";
import { prisma } from "../lib/prisma";
import { asyncHandler } from "../lib/asyncHandler";
import { getAiService } from "../openai";
import { readMediaBufferByUrl } from "../lib/mediaStorage";

export const mediaRouter = Router();

const CATEGORIES = [
  "PROPERTY_OVERVIEW",
  "LAWN",
  "HEDGE",
  "BED",
  "DRIVEWAY",
  "PROBLEM_AREA",
  "BEFORE",
  "DAMAGE",
  "OTHER",
] as const;

mediaRouter.patch(
  "/:id",
  asyncHandler(async (req, res) => {
    const data = z.object({ category: z.enum(CATEGORIES).optional(), propertyId: z.string().optional() }).parse(req.body);
    const media = await prisma.mediaAsset.update({ where: { id: req.params.id }, data });
    res.json(media);
  })
);

// Optional, explicitly non-binding image description - never used to derive
// a binding area, effort, or price (enforced in the prompt + the flag below).
mediaRouter.post(
  "/:id/describe",
  asyncHandler(async (req, res) => {
    const media = await prisma.mediaAsset.findUniqueOrThrow({ where: { id: req.params.id } });
    const description = await getAiService().describeImage(media.storageUrl);
    const updated = await prisma.mediaAsset.update({
      where: { id: media.id },
      data: { aiDescription: description, aiDescriptionIsEstimate: true },
    });
    res.json(updated);
  })
);

mediaRouter.post(
  "/messages/:messageId/transcribe",
  asyncHandler(async (req, res) => {
    const message = await prisma.message.findUniqueOrThrow({ where: { id: req.params.messageId } });
    if (!message.mediaUrl) return res.status(400).json({ error: "Keine Audiodatei vorhanden" });

    const buffer = await readMediaBufferByUrl(message.mediaUrl);
    const transcriptText = await getAiService().transcribeAudio(buffer, "audio/ogg");
    const transcript = await prisma.voiceTranscript.upsert({
      where: { messageId: message.id },
      update: { transcriptText, isAutoGenerated: true, correctedByUser: false },
      create: { messageId: message.id, transcriptText, isAutoGenerated: true },
    });
    res.json(transcript);
  })
);

mediaRouter.patch(
  "/voice-transcripts/:id",
  asyncHandler(async (req, res) => {
    const transcriptText = z.string().min(1).parse(req.body.transcriptText);
    const transcript = await prisma.voiceTranscript.update({
      where: { id: req.params.id },
      data: { transcriptText, correctedByUser: true },
    });
    res.json(transcript);
  })
);
